const translations = { en, zh, ja, es, fr, pt, hi }

export function t(key, lang) {
  const keys = key.split('.')
  let val = translations[lang]
  if (!val) val = translations.en
  for (const k of keys) {
    if (!val) return key
    val = val[k]
  }
  return val || key
}